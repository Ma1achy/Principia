//! The fragment's generated snippets (TASK-M2-25; R-116, REQ-SYS-085): `cargo xtask build-kernel` lifts the fragment
//! decode, encode and shape map out of the kernel's translation (`xtask::fragment_wgsl`) and fails when a checked-in
//! snippet differs from it.
//!
//! - `fragment_wgsl_check_fails_on_a_hand_edit`: `fragment_wgsl::check` passes files equal to their translation, fails
//!   naming a file edited by hand or missing, and with `--bless` rewrites them. Control: a hand edit passes.
//! - `fragment_wgsl_snippets_are_checked_in`: the snippets of `target/spirv/kernel.spv` are the checked-in files, each
//!   under the generated header, each chart's section present in `decode.wgsl`. Control: a snippet one byte off is
//!   found. It reads `target/spirv/kernel.spv`, so `cargo xtask build-kernel` runs first, as CI runs it.

use std::fs;
use std::path::{Path, PathBuf};

use validation::negative_control;
use xtask::fragment_wgsl::{
    check, section_end, section_start, snippets, DECODE_CHARTS, DECODE_FILE, ENCODE_FILE,
    SHAPE_FILE,
};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

/// A fresh scratch directory under the test's target directory.
fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir
}

/// The check over two files: equal, then `edit`ed by hand, then one missing, then blessed.
fn check_case(dir: &str, edit: &str) {
    let root = scratch(dir);
    let fresh = vec![
        ("a/one.wgsl", "fn one() {}\n".to_owned()),
        ("b/two.wgsl", "fn two() {}\n".to_owned()),
    ];
    for (path, text) in &fresh {
        fs::create_dir_all(root.join(path).parent().unwrap()).unwrap();
        fs::write(root.join(path), text).unwrap();
    }
    assert_eq!(check(&root, &fresh, false), Ok(vec![]));
    fs::write(root.join("b/two.wgsl"), format!("fn two() {{}}\n{edit}")).unwrap();
    let err = check(&root, &fresh, false).expect_err("a hand edit passes the check");
    assert!(
        err.contains("b/two.wgsl") && !err.contains("a/one.wgsl"),
        "{err}"
    );
    assert!(err.contains("--bless"), "{err}");
    fs::remove_file(root.join("a/one.wgsl")).unwrap();
    let err = check(&root, &fresh, false).expect_err("a missing snippet passes");
    assert!(
        err.contains("a/one.wgsl") && err.contains("b/two.wgsl"),
        "{err}"
    );
    assert_eq!(
        check(&root, &fresh, true),
        Ok(vec!["a/one.wgsl".to_owned(), "b/two.wgsl".to_owned()])
    );
    for (path, text) in &fresh {
        assert_eq!(&fs::read_to_string(root.join(path)).unwrap(), text);
    }
    assert_eq!(check(&root, &fresh, false), Ok(vec![]));
    assert_eq!(check(&root, &fresh, true), Ok(vec![]));
}

#[test]
fn fragment_wgsl_check_fails_on_a_hand_edit() {
    check_case("fragment-wgsl-check", "// edited\n");
}

negative_control!(
    fragment_wgsl_check_fails_on_a_hand_edit,
    "an edit that changes nothing must not stand for a hand edit: the check then passes",
    expected = "a hand edit passes the check",
    check_case("fragment-wgsl-check-control", "")
);

/// The snippets of the built kernel against the checked-in files, `alter` applied to the translation first.
fn check_snippets(alter: impl Fn(&mut String)) {
    let root = root();
    let spv = fs::read(root.join("target/spirv/kernel.spv"))
        .expect("target/spirv/kernel.spv: run `cargo xtask build-kernel` first");
    let mut fresh = snippets(&spv).unwrap();
    let files: Vec<&str> = fresh.iter().map(|f| f.0).collect();
    assert_eq!(files, [DECODE_FILE, ENCODE_FILE, SHAPE_FILE]);
    for (_, text) in &mut fresh {
        alter(text);
        assert!(
            text.starts_with("// GENERATED by `cargo xtask build-kernel`"),
            "a snippet lacks the generated header"
        );
    }
    for (section, _) in DECODE_CHARTS {
        let decode = &fresh[0].1;
        let open = decode.find(&section_start(section));
        let close = decode.find(&section_end(section));
        assert!(
            open.zip(close).is_some_and(|(o, c)| o < c),
            "decode.wgsl has no section {section}"
        );
    }
    check(&root, &fresh, false).expect("the checked-in snippets are the translation's");
}

#[test]
fn fragment_wgsl_snippets_are_checked_in() {
    check_snippets(|_| {});
}

negative_control!(
    fragment_wgsl_snippets_are_checked_in,
    "a snippet one byte off its translation must be found",
    expected = "the checked-in snippets are the translation's",
    check_snippets(|t| t.push(' '))
);
