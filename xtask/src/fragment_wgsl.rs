//! The fragment snippets `cargo xtask build-kernel` emits from the translation (R-116; REQ-COL-006, REQ-SYS-085): the
//! decode, the descriptor, the encode and the shape map of `crates/kernel/src/stage/fragment.rs`, each compiled from the
//! one Rust source by rust-gpu to SPIR-V and read back by naga, then lifted out of the kernel's module into a WGSL
//! snippet the fragment assembler places. Nothing in a snippet is written by hand: its body is naga's translation of
//! the entry point's, and its glue only moves values in and out of the body's words at the offsets of the ledger's
//! layout table (`ledger::fragment`), the table the kernel's constants are generated from.
//!
//! **The lift** ([`lift`]). The module is cut to the one entry point (naga's `compact`), whose wrapper calls the body;
//! the body becomes a plain function of its words, `<prefix>_body(words_in: <prefix>_words) -> <prefix>_words`: the
//! entry point's sized storage array becomes the function's argument, copied into a local the body reads and writes and
//! returns (`localise`), so the snippet keeps no global state and stores to no global; its uniform, where it has one,
//! keeps its type and is rebound at the fragment's [`DECODE_UNIFORMS`] group and binding; and every type takes a name
//! under the prefix (the words' struct `<prefix>_words`, its array the member `w`), so snippets placed side by side, and
//! the shader around them, share no name.
//!
//! **The files** ([`snippets`]): `crates/render/wgsl/decode.wgsl` (one section per chart the DECODE preset draws, each
//! defining `frag_decode(uv)`, the descriptor's section, `frag_describe`, and the free decode's, `frag_decode_free(z)`,
//! the ROUNDTRIP preset's second `D`), `crates/render/wgsl/encode.wgsl`
//! (`frag_encode`) and `crates/ledger/wgsl/shape.wgsl` (`shape(r, m)`, the read side's shape map). They are checked in,
//! so the render and ledger crates build without rust-gpu, and [`check`] fails the build when one differs from its
//! translation: a hand edit, or a kernel change not re-emitted (`cargo xtask build-kernel --bless` writes them).

