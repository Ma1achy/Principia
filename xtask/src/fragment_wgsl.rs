/// Every snippet file's first lines.
pub fn header(what: &str) -> String {
    format!(
        "// GENERATED by `cargo xtask build-kernel` (xtask/src/fragment_wgsl.rs): {what}, translated from the one Rust\n\
         // source, crates/kernel/src/stage/fragment.rs, through rust-gpu → SPIR-V → naga (R-116). Never edit it by hand:\n\
         // build-kernel fails when it differs from the translation; `cargo xtask build-kernel --bless` re-emits it.\n"
    )
}

/// `entry`'s body lifted out of `module` as WGSL under `prefix` (the module's note): `<prefix>_body(words_in)`, its words
/// the struct `<prefix>_words` (array member `w`), its uniform, if any, `<prefix>_uniforms` at [`DECODE_UNIFORMS`].
pub fn lift(module: &Module, entry: &str, prefix: &str) -> Result<String, String> {
    let mut m = module.clone();
    let at = m
        .entry_points
        .iter()
        .position(|e| e.name.replace("::", "_") == entry)
        .ok_or_else(|| format!("the kernel's module has no entry point `{entry}`"))?;
    let kept = m.entry_points.swap_remove(at);
    m.entry_points.clear();
    m.entry_points.push(kept);
    naga::compact::compact(&mut m, naga::compact::KeepUnused::No);
    let ep = m
        .entry_points
        .pop()
        .ok_or("compaction dropped the entry point")?;
    let body = ep
        .function
        .body
        .iter()
        .find_map(|s| match s {
            Statement::Call { function, .. } => Some(*function),
            _ => None,
        })
        .ok_or_else(|| format!("`{entry}`'s wrapper calls no body"))?;
    if !ep.function.arguments.is_empty() {
        return Err(format!(
            "`{entry}` takes arguments: a fragment export reads only its words and uniform"
        ));
    }
    let mut words = None;
    let mut kept = naga::Arena::new();
    let mut moved = std::collections::HashMap::new();
    for (h, g) in m.global_variables.iter() {
        match g.space {
            AddressSpace::Storage { .. } if words.is_none() => words = Some((h, g.ty)),
            AddressSpace::Storage { .. } => {
                return Err(format!(
                    "`{entry}` has two storage arrays: a fragment export has one, its words"
                ))
            }
            AddressSpace::Uniform => {
                let mut g = g.clone();
                g.binding = Some(ResourceBinding {
                    group: DECODE_UNIFORMS.0,
                    binding: DECODE_UNIFORMS.1,
                });
                g.name = Some(format!("{prefix}_uniforms"));
                moved.insert(h, kept.append(g, naga::Span::UNDEFINED));
            }
            other => {
                return Err(format!(
                    "`{entry}` reads a global in {other:?}: a fragment export reads only its words and uniform"
                ))
            }
        }
    }
    let (words, words_ty) =
        words.ok_or_else(|| format!("`{entry}` has no storage array, its words"))?;
    let f = m.functions.get_mut(body);
    f.name = Some(format!("{prefix}_body"));
    localise(f, words, words_ty, &moved);
    m.global_variables = kept;
    let handles: Vec<_> = m.types.iter().map(|(h, _)| h).collect();
    for (k, h) in handles.into_iter().enumerate() {
        let mut ty: Type = m.types[h].clone();
        ty.name = Some(format!("{prefix}_t{k}"));
        if h == words_ty {
            ty.name = Some(format!("{prefix}_words"));
            if let TypeInner::Struct { members, .. } = &mut ty.inner {
                if let [only] = members.as_mut_slice() {
                    only.name = Some("w".to_owned());
                }
            }
        }
        m.types.replace(h, ty);
    }
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::default(),
    )
    .validate(&m)
    .map_err(|e| format!("naga rejected `{entry}`'s lifted body: {e:?}"))?;
    naga::back::wgsl::write_string(&m, &info, naga::back::wgsl::WriterFlags::empty())
        .map_err(|e| format!("naga could not write `{entry}`'s lifted body: {e}"))
}

/// Makes the body `f` a function of its words: `words_in` its argument, copied into a local `words` that every access
/// of the global `words` now reads and writes, and returned at each `return`, so the lifted body stores to no global
/// (REQ-RENDER-001: the read side emits no setter). Each other global the body reads, its uniform, is `moved` to its
/// handle in the cut arena.
fn localise(
    f: &mut Function,
    words: Handle<GlobalVariable>,
    ty: Handle<Type>,
    moved: &std::collections::HashMap<Handle<GlobalVariable>, Handle<GlobalVariable>>,
) {
    let span = naga::Span::UNDEFINED;
    let local = f.local_variables.append(
        LocalVariable {
            name: Some("words".to_owned()),
            ty,
            init: None,
        },
        span,
    );
    for (_, e) in f.expressions.iter_mut() {
        if let Expression::GlobalVariable(g) = *e {
            // `lift` admits only the words and the uniform, so a global not moved is the words.
            *e = match moved.get(&g) {
                Some(&to) => Expression::GlobalVariable(to),
                None => {
                    debug_assert_eq!(g, words, "a global neither moved nor the words");
                    Expression::LocalVariable(local)
                }
            };
        }
    }
    let pointer = f.expressions.append(Expression::LocalVariable(local), span);
    f.arguments.push(FunctionArgument {
        name: Some("words_in".to_owned()),
        ty,
        binding: None,
    });
    let argument = f.expressions.append(Expression::FunctionArgument(0), span);
    let mut body = std::mem::take(&mut f.body);
    returning(&mut body, &mut f.expressions, pointer);
    let mut start = Block::from_vec(vec![Statement::Store {
        pointer,
        value: argument,
    }]);
    start.append(&mut body);
    f.body = start;
    f.result = Some(FunctionResult { ty, binding: None });
}

/// Each `return` in `block`, at any depth, made `return words;`: a load of `pointer`, emitted just before it.
fn returning(
    block: &mut Block,
    expressions: &mut naga::Arena<Expression>,
    pointer: Handle<Expression>,
) {
    let old = std::mem::take(block);
    for (statement, span) in old.span_into_iter() {
        match statement {
            Statement::Return { value: None } => {
                let load = expressions.append(Expression::Load { pointer }, span);
                block.push(
                    Statement::Emit(naga::Range::new_from_bounds(load, load)),
                    span,
                );
                block.push(Statement::Return { value: Some(load) }, span);
            }
            Statement::Block(mut b) => {
                returning(&mut b, expressions, pointer);
                block.push(Statement::Block(b), span);
            }
            Statement::If {
                condition,
                mut accept,
                mut reject,
            } => {
                returning(&mut accept, expressions, pointer);
                returning(&mut reject, expressions, pointer);
                block.push(
                    Statement::If {
                        condition,
                        accept,
                        reject,
                    },
                    span,
                );
            }
            Statement::Switch {
                selector,
                mut cases,
            } => {
                for c in &mut cases {
                    returning(&mut c.body, expressions, pointer);
                }
                block.push(Statement::Switch { selector, cases }, span);
            }
            Statement::Loop {
                mut body,
                continuing,
                break_if,
            } => {
                returning(&mut body, expressions, pointer);
                block.push(
                    Statement::Loop {
                        body,
                        continuing,
                        break_if,
                    },
                    span,
                );
            }
            other => block.push(other, span),
        }
    }
}

/// The WGSL reading word `at` of `words` as an f32.
fn f(words: &str, at: usize) -> String {
    format!("bitcast<f32>({words}.w[{at}])")
}

/// The WGSL reading the fifteen `(m, r, p)` words from `at` of `words` into `out`'s `m`, `r` and `p`.
fn read_ic(out: &mut String, var: &str, words: &str, at: usize) {
    let _ = writeln!(
        out,
        "    {var}.m = vec3<f32>({}, {}, {});",
        f(words, at),
        f(words, at + 1),
        f(words, at + 2)
    );
    for b in 0..3 {
        let _ = writeln!(
            out,
            "    {var}.r[{b}] = vec2<f32>({}, {});",
            f(words, at + 3 + 2 * b),
            f(words, at + 4 + 2 * b)
        );
    }
    for b in 0..3 {
        let _ = writeln!(
            out,
            "    {var}.p[{b}] = vec2<f32>({}, {});",
            f(words, at + 9 + 2 * b),
            f(words, at + 10 + 2 * b)
        );
    }
}

/// The WGSL writing `(m, r, p)` into the fifteen words from `at` of `words`.
fn write_ic(out: &mut String, words: &str, at: usize) {
    for (k, v) in ["m.x", "m.y", "m.z"].iter().enumerate() {
        let _ = writeln!(out, "    {words}.w[{}] = bitcast<u32>({v});", at + k);
    }
    for b in 0..3 {
        let _ = writeln!(
            out,
            "    {words}.w[{}] = bitcast<u32>(r[{b}].x);",
            at + 3 + 2 * b
        );
        let _ = writeln!(
            out,
            "    {words}.w[{}] = bitcast<u32>(r[{b}].y);",
            at + 4 + 2 * b
        );
    }
    for b in 0..3 {
        let _ = writeln!(
            out,
            "    {words}.w[{}] = bitcast<u32>(p[{b}].x);",
            at + 9 + 2 * b
        );
        let _ = writeln!(
            out,
            "    {words}.w[{}] = bitcast<u32>(p[{b}].y);",
            at + 10 + 2 * b
        );
    }
}

/// The descriptor's twelve fields, in the generated `ICDescriptor`'s order (kernel `stage::fragment::write_fields`).
pub const DESCRIPTOR_FIELDS: [&str; 12] = [
    "m0",
    "m1",
    "m2",
    "q_mass",
    "rho_mag",
    "lambda_mag",
    "rho_ratio",
    "rho_angle",
    "K_0",
    "V_0",
    "virial_ratio",
    "r_min_pair_0",
];

/// The WGSL reading the twelve descriptor words from `at` of `words` into `var`, each field as its stored bits, so a
/// caller tests a pole value on its bits (R-436).
fn read_descriptor(out: &mut String, var: &str, words: &str, at: usize) {
    for (k, name) in DESCRIPTOR_FIELDS.iter().enumerate() {
        let _ = writeln!(out, "    {var}.{name} = {words}.w[{}];", at + k);
    }
}

/// The structs the decode's sections return: the decode stage's offsets (kernel `stage::fragment`).
