//! The colour-vision simulation (TASK-M7-20; dd_colouring §3.8; R-78, R-123, R-383, R-386): the pass's WGSL,
//! `shaders/wgsl/compositor/cvd.wgsl`, run on the GPU, and its CPU mirror, `render::display::cvd`, against the golden
//! values in `fixtures/cvd/goldens.json`, generated from the reference implementation R-383 pins (DaltonLens-Python at
//! commit `3cba5e6`, in linear sRGB, through its simulators' linear-RGB path):
//! - REQ-COL-042, dd_colouring unit test 10 (`cvd_simulation_*`): protan, deutan and tritan match the goldens, the
//!   matrices and the simulated colours; achromatopsia yields `R = G = B` exactly; the stage takes linear colour, so a
//!   simulation applied before linearisation is a detectable difference.
//! - REQ-COL-045 (`cvd_modes_*`): the Display window's five modes, and the pass transforming a test colour set under
//!   each, by the mode's uniform: Viénot or Brettel matching the goldens, `M_achrom` grey, off the identity.
//! - REQ-COL-061 (`cvd_hatch_distinct_*`): under each simulation, the hatch stays distinguishable from every palette
