// ── REQ-COL-061: the hatch under each simulation (R-386; R-71, proposed) ───────────────────────────────────────────

/// The OKLab distance between two linear colours.
fn oklab_distance(a: Rgb, b: Rgb) -> f64 {
    let (p, q) = (present::linear_to_oklab(a), present::linear_to_oklab(b));
    ((p[0] - q[0]).powi(2) + (p[1] - q[1]).powi(2) + (p[2] - q[2]).powi(2)).sqrt()
}

/// What the screen shows of the linear colour `c` under `mode`: simulated, then clamped to [0, 1], as the pass writes.
fn seen(mode: CvdMode, c: Rgb) -> Rgb {
    cvd::simulate(mode, c).map(|x| x.clamp(0.0, 1.0))
}

/// REQ-COL-061's threshold (proposed, R-71; R-386): the OKLab distance from R-16's flat magenta `#FF00FF` to body-1
/// escape's `#E034C6`, 0.101, the distance R-132 ruled a collision and REQ-COL-055's bound, taken unsimulated.
fn tau() -> f64 {
    oklab_distance(hex(0xFF00FF), hex(0xE034C6))
}

/// The hatch as seen under one mode: each stripe colour's least OKLab distance to a palette entry and that entry's
/// name, both simulated, and the two simulated stripes' distance from each other, the pattern's contrast.
struct Seen {
    nearest: [(f64, String); 2],
    stripes: f64,
}

fn measure(mode: CvdMode, hatch: [Rgb; 2], entries: &[(String, Rgb)]) -> Seen {
    let labs: Vec<Rgb> = entries
        .iter()
        .map(|(_, p)| present::linear_to_oklab(seen(mode, *p)))
        .collect();
    let nearest = hatch.map(|h| {
        let q = present::linear_to_oklab(seen(mode, h));
        labs.iter()
            .zip(entries)
            .map(|(p, (name, _))| {
                let d =
                    ((p[0] - q[0]).powi(2) + (p[1] - q[1]).powi(2) + (p[2] - q[2]).powi(2)).sqrt();
                (d, name.clone())
            })
            .fold((f64::INFINITY, String::new()), |a, b| {
                if b.0 < a.0 {
                    b
                } else {
                    a
                }
            })
    });
    Seen {
        nearest,
        stripes: oklab_distance(seen(mode, hatch[0]), seen(mode, hatch[1])),
    }
}

/// REQ-COL-061's criterion (proposed, R-71; R-386), under each simulation: the hatch is distinguishable from the
/// palette if each stripe colour is farther than [`tau`] from every palette entry, both simulated; and where a stripe
/// colour falls within it, the pattern counts: the hatch is still distinguishable if its two stripes, simulated, are
/// farther than [`tau`] apart, since it then shows as diagonal stripes, which no palette entry draws, each drawing one
/// flat colour. Under achromatopsia every stripe colour falls within it (the grey ramp), and the pattern's contrast is
/// its lightness step under `M_achrom`. Each mode's distances are printed, the proposal's evidence.
fn check_hatch_distinct(colours: [[u8; 3]; 2]) {
    let entries = palettes::entries();
    let hatch = colours.map(present::srgb8);
    let tau = tau();
    let hexes = colours.map(|c| format!("#{:02X}{:02X}{:02X}", c[0], c[1], c[2]));
    eprintln!("REQ-COL-061: threshold {tau:.4}, #FF00FF from #E034C6 (R-132's collision)");
    for mode in SIMULATIONS {
        let m = measure(mode, hatch, &entries);
        let clear = m.nearest.iter().all(|(d, _)| *d > tau);
        let pattern = m.stripes > tau;
        eprintln!(
            "{}: {} {:.4} from {}; {} {:.4} from {}; stripes {:.4} apart; {}",
            mode.label(),
            hexes[0],
            m.nearest[0].0,
            m.nearest[0].1,
            hexes[1],
            m.nearest[1].0,
            m.nearest[1].1,
            m.stripes,
            match (clear, pattern) {
                (true, _) => "distinct by colour",
                (false, true) => "distinct by its pattern",
                (false, false) => "NOT distinct",
            }
        );
        assert!(
            clear || pattern,
            "the hatch {} / {} is not distinguishable under {}: {:.4} from {} and {:.4} from {}, its stripes {:.4} \
             apart, the threshold {tau:.4}",
            hexes[0],
            hexes[1],
            mode.label(),
            m.nearest[0].0,
            m.nearest[0].1,
            m.nearest[1].0,
            m.nearest[1].1,
            m.stripes
        );
    }
}

