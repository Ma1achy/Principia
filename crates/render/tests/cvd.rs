/// The f32 unit roundoff, `2⁻²⁴`.
const U: f64 = f32::EPSILON as f64 / 2.0;

/// The f64 roundoff of a matrix entry that is zero in exact arithmetic: the reference's are below `2e-16`.
const NOISE: f64 = 1e-15;

/// The f64 agreement asked of the mirror with the reference: both compute the same products in f64, by different
/// routes (numpy's LAPACK inverse, this crate's adjugate), so they agree to a few f64 roundings of the largest term;
/// `1e-12` relative to the larger of 1 and the value, the inverse's entries reaching 69.
fn close64(a: f64, b: f64) -> bool {
    (a - b).abs() <= 1e-12 * a.abs().max(b.abs()).max(1.0)
}

// ── REQ-COL-042: the matrices and the simulated colours (dd_colouring unit test 10) ────────────────────────────────

fn check_mat(name: &str, got: &Mat3, want: &Mat3) {
    for i in 0..3 {
        for j in 0..3 {
            assert!(
                close64(got[i][j], want[i][j]),
                "{name}[{i}][{j}] is {}, the reference's {}",
                got[i][j],
                want[i][j]
            );
        }
    }
}

fn check_vec(name: &str, got: &[f64; 3], want: &[f64; 3]) {
    check_mat(name, &[*got; 3], &[*want; 3]);
}

