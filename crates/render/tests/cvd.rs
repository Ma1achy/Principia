/// The pass, drawn on a float layer of the test colours (linear, as the reference decoded them) into a float screen,
/// under each mode by its uniform: within the f32 bound of `expect(mode, colour)`, clamped to [0, 1] as the pass
/// clamps; off exactly the colour; achromatopsia `R = G = B` exactly.
fn check_pass_modes(gpu: &GpuHarness, expect: fn(&Colour, CvdMode) -> Rgb) {
    let colours = goldens().colours;
    for mode in CvdMode::ALL {
        let got = run_float_stage(gpu, &colours, mode);
        for (c, g) in colours.iter().zip(&got) {
            let want = expect(c, mode).map(|x| x.clamp(0.0, 1.0));
            let b = bound(mode, c.linear);
            assert!(
                (0..3).all(|j| (g[j] - want[j]).abs() <= b[j]),
                "the pass's {} of {:?} is {g:?}, not {want:?}",
                mode.label(),
                c.srgb8
            );
            if mode == CvdMode::Achromatopsia {
                assert!(
                    g[0] == g[1] && g[1] == g[2],
                    "the pass's achromatopsia of {:?} is {g:?}",
                    c.srgb8
                );
            }
        }
    }
}

/// What each mode should make of a test colour: the reference's golden, `M_achrom`'s grey (the mirror, checked
/// against the row above), or the colour (off), with each colour rounded to f32 as the float layer holds it.
fn expected(c: &Colour, mode: CvdMode) -> Rgb {
    match mode {
        CvdMode::Off => c.linear.map(|x| f64::from(x as f32)),
        CvdMode::Achromatopsia => cvd::simulate(mode, c.linear),
        _ => c.golden(mode).unwrap(),
    }
}

/// The pass on an `Rgba32Float` layer of `colours`' linear values into an `Rgba32Float` screen, under `mode`.
fn run_float_stage(gpu: &GpuHarness, colours: &[Colour], mode: CvdMode) -> Vec<Rgb> {
    use wgpu::util::DeviceExt;
    let (device, queue) = (gpu.device(), gpu.queue());
    let format = wgpu::TextureFormat::Rgba32Float;
    let size = wgpu::Extent3d {
        width: colours.len() as u32,
        height: 1,
        depth_or_array_layers: 1,
    };
    let texels: Vec<u8> = colours
        .iter()
        .flat_map(|c| {
            [
                c.linear[0] as f32,
                c.linear[1] as f32,
                c.linear[2] as f32,
                1.0,
            ]
        })
        .flat_map(f32::to_le_bytes)
        .collect();
    let descriptor = |label, usage| wgpu::TextureDescriptor {
        label: Some(label),
        size,
        mip_level_count: 1,
        sample_count: 1,
        dimension: wgpu::TextureDimension::D2,
        format,
        usage,
        view_formats: &[],
    };
    let source = device.create_texture_with_data(
        queue,
        &descriptor("layer", wgpu::TextureUsages::TEXTURE_BINDING),
        wgpu::util::TextureDataOrder::LayerMajor,
        &texels,
    );
    let screen = device.create_texture(&descriptor(
        "screen",
        wgpu::TextureUsages::RENDER_ATTACHMENT | wgpu::TextureUsages::COPY_SRC,
    ));
    let row = (16 * colours.len() as u32).next_multiple_of(256);
    let staging = device.create_buffer(&wgpu::BufferDescriptor {
        label: Some("screen readback"),
        size: u64::from(row),
        usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
        mapped_at_creation: false,
    });
    let pass = CvdPass::new(device, format).unwrap_or_else(|e| panic!("{e}"));
    let mut encoder = device.create_command_encoder(&Default::default());
    pass.draw(
        device,
        &mut encoder,
        &source.create_view(&Default::default()),
        &screen.create_view(&Default::default()),
        mode,
    );
    encoder.copy_texture_to_buffer(
        screen.as_image_copy(),
        wgpu::TexelCopyBufferInfo {
            buffer: &staging,
            layout: wgpu::TexelCopyBufferLayout {
                offset: 0,
                bytes_per_row: Some(row),
                rows_per_image: None,
            },
        },
        size,
    );
    queue.submit([encoder.finish()]);
    let slice = staging.slice(..);
    slice.map_async(wgpu::MapMode::Read, |r| r.expect("the readback maps"));
    device
        .poll(wgpu::PollType::wait_indefinitely())
        .expect("the device polls");
    let bytes = slice
        .get_mapped_range()
        .expect("the readback maps")
        .to_vec();
    let f = |k: usize| {
        f64::from(f32::from_le_bytes([
            bytes[k],
            bytes[k + 1],
            bytes[k + 2],
            bytes[k + 3],
        ]))
    };
    (0..colours.len())
        .map(|k| [f(16 * k), f(16 * k + 4), f(16 * k + 8)])
        .collect()
}

