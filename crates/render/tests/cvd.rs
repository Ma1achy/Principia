// ── the WGSL on the GPU ─────────────────────────────────────────────────────────────────────────────────────────────

/// The test entry appended to the pass's WGSL: pixel `k` of a `WIDTH`-wide target evaluates `cvd_sim` on case `k`,
/// whose x, y, z are the colour's f32 bits and w the mode's code, and returns the result's bits.
const ENTRY: &str = r"
@group(1) @binding(0) var<storage, read> cvd_cases: array<vec4<u32>>;

@fragment
fn t_cvd(@builtin(position) pos: vec4<f32>) -> @location(0) vec4<u32> {
    let v = cvd_cases[u32(pos.y) * 64u + u32(pos.x)];
    return vec4<u32>(bitcast<vec3<u32>>(cvd_sim(v.w, bitcast<vec3<f32>>(v.xyz))), 0u);
}
";

/// The test entry's target width, in cases per row.
const WIDTH: usize = 64;

/// The pass's WGSL, with at most one mutation, a control's: `from` replaced by `to`, which the text must contain.
#[derive(Clone, Copy, Debug)]
struct Text {
    from: &'static str,
    to: &'static str,
}

const AS_IS: Text = Text { from: "", to: "" };

#[cfg(feature = "controls")]
fn mutated(from: &'static str, to: &'static str) -> Text {
    assert!(
        cvd::CVD_WGSL.contains(from),
        "the WGSL has no `{from}` to mutate"
    );
    Text { from, to }
}

impl Text {
    fn source(self) -> String {
        if self.from.is_empty() {
            cvd::CVD_WGSL.to_string()
        } else {
            cvd::CVD_WGSL.replacen(self.from, self.to, 1)
        }
    }
}

fn gpu() -> GpuHarness {
    GpuHarness::new().expect("a GPU device")
}

/// `cvd_sim(mode, c)` on the GPU for each `(mode, c)`, in f64.
fn run_sim(gpu: &GpuHarness, text: Text, cases: &[(CvdMode, Rgb)]) -> Vec<Rgb> {
    let module = format!("{}\n{ENTRY}", text.source());
    let rows = cases.len().div_ceil(WIDTH);
    let mut words = vec![0u32; rows * WIDTH * 4];
    for (k, (mode, c)) in cases.iter().enumerate() {
        for j in 0..3 {
            words[4 * k + j] = (c[j] as f32).to_bits();
        }
        words[4 * k + 3] = mode.code();
    }
    let kernel = gpu
        .fragment(
            &module,
            "t_cvd",
            &[&[], &[BindingKind::Storage]],
            WIDTH as u32,
            rows as u32,
        )
        .unwrap_or_else(|e| panic!("{e:?}"));
    let out = kernel
        .draw(&[&[], &[&words]])
        .unwrap_or_else(|e| panic!("{e:?}"));
    out[..cases.len()]
        .iter()
        .map(|p| [0, 1, 2].map(|j| f64::from(f32::from_bits(p[j]))))
        .collect()
}

/// The worst-case f32 error of `m · c` against the f64 product: the colour's and the matrix's roundings to f32 and the
/// three products and two sums, `5U` relative each at most, so `8U · Σⱼ |mᵢⱼ| |cⱼ|` with room; for Brettel, the larger
/// of its two transforms', which agree on the separating plane, so a colour near it may take either. A simulation adds
/// [`NOISE`]` · Σⱼ |cⱼ|` for the entries that are zero in exact arithmetic (Viénot's third column above its diagonal,
/// blue being on the plane), which the reference holds as f64 roundoff and the mirror computes by another route.
fn bound(mode: CvdMode, c: Rgb) -> Rgb {
    let m = Matrices::get();
    let row = |mat: &Mat3, i: usize| (0..3).map(|j| mat[i][j].abs() * c[j].abs()).sum::<f64>();
    std::array::from_fn(|i| {
        8.0 * U
            * match mode {
                CvdMode::Off => 0.0,
                CvdMode::Deuteranopia => row(&m.vienot_deutan, i),
                CvdMode::Protanopia => row(&m.vienot_protan, i),
                CvdMode::Tritanopia => {
                    row(&m.brettel_tritan.t1, i).max(row(&m.brettel_tritan.t2, i))
                }
                CvdMode::Achromatopsia => row(&[cvd::ACHROM_ROW; 3], i),
            }
            + match mode {
                CvdMode::Off => 0.0,
                _ => NOISE * (c[0].abs() + c[1].abs() + c[2].abs()),
            }
    })
}

/// `cvd_sim` on the GPU gives each test colour the reference's protan, deutan and tritan, within the f32 bound.
fn check_gpu_goldens(gpu: &GpuHarness, text: Text) {
    let colours = goldens().colours;
    let cases: Vec<(CvdMode, Rgb)> = DICHROMACIES
        .iter()
        .flat_map(|&m| colours.iter().map(move |c| (m, c.linear)))
        .collect();
    let got = run_sim(gpu, text, &cases);
    for (k, &(mode, c)) in cases.iter().enumerate() {
        let want = colours[k % colours.len()].golden(mode).unwrap();
        let b = bound(mode, c);
        assert!(
            (0..3).all(|j| (got[k][j] - want[j]).abs() <= b[j]),
            "the GPU's {} of {:?} is {:?}, the reference's {want:?}, beyond {b:?}",
            mode.label(),
            colours[k % colours.len()].srgb8,
            got[k]
        );
    }
}

