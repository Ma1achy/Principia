/// Colours beyond the goldens' lattice for the achromatopsia check: a 17-step lattice, every 8-bit grey's neighbours
/// included.
fn lattice17() -> Vec<Rgb> {
    let s = |k: usize| present::srgb_to_linear(k as f64 / 16.0);
    (0..17 * 17 * 17)
        .map(|k| [s(k / 289), s(k / 17 % 17), s(k % 17)])
        .collect()
}

/// Achromatopsia yields `R = G = B` exactly, on the GPU and in the mirror, and the grey is `M_achrom`'s, within the
/// f32 bound on the GPU.
fn check_achrom(gpu: &GpuHarness, text: Text) {
    let colours: Vec<Rgb> = goldens()
        .colours
        .iter()
        .map(|c| c.linear)
        .chain(lattice17())
        .collect();
    let cases: Vec<(CvdMode, Rgb)> = colours
        .iter()
        .map(|&c| (CvdMode::Achromatopsia, c))
        .collect();
    let got = run_sim(gpu, text, &cases);
    for (c, g) in colours.iter().zip(&got) {
        let want =
            cvd::ACHROM_ROW[0] * c[0] + cvd::ACHROM_ROW[1] * c[1] + cvd::ACHROM_ROW[2] * c[2];
        let cpu = cvd::simulate(CvdMode::Achromatopsia, *c);
        assert!(
            g[0].to_bits() == g[1].to_bits() && g[1].to_bits() == g[2].to_bits(),
            "the GPU's achromatopsia of {c:?} is {g:?}, not R = G = B"
        );
        assert!(
            cpu[0].to_bits() == cpu[1].to_bits() && cpu[1].to_bits() == cpu[2].to_bits(),
            "the mirror's achromatopsia of {c:?} is {cpu:?}, not R = G = B"
        );
        assert!(
            (g[0] - want).abs() <= bound(CvdMode::Achromatopsia, *c)[0] && close64(cpu[0], want),
            "achromatopsia of {c:?} is {g:?} on the GPU and {cpu:?} in the mirror, not M_achrom's {want}"
        );
    }
}

