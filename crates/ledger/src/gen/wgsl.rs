//! The WGSL emitter (dd_generation_root §1: one source, two language targets; render contract Part 5, "Unpack layer";
//! payload §6): writes the fragment-side unpack layer, `crates/render/frag/generated/payload_unpack.wgsl`, from the
//! same ledger the Rust emitter ([`super::rust`]) reads. It holds the payload schema version, the stored `SimState`
//! layouts and `ICDescriptor`, the `SimState` and word buffer bindings, the `sd_*`, `pa_`/`pb_`/`tm_` and `fgw_*`
//! accessors with payload §6's names (R-86), and payload §3's frozen continuation table as shader constants.
//!
//! The WGSL traps (render contract Part 5; payload §6) hold by construction: every `extractBits` takes a u32, no f64
//! is written, f16 pairs are read through core `unpack2x16float` with no `enable f16`, `r`, `p` and the shadow are
//! `array<vec2<f32>, 3>`, and the word buffer is its own binding, indexed by the sample index the `SimState` buffer is.
//! `cargo xtask lint wgsl` checks them over naga's IR.
//!
//! RQ-188 (open): the corpus gives no binding numbers, nor which `SimState` variant the layer binds, nor the WGSL form
//! of the u16 `closure_step` and of the u64 schema version. This emitter writes RQ-188's recommended options, marked in
//! the output as waiting on it.

use std::fmt::Write as _;
use std::path::PathBuf;

use crate::gen::rust::{self, PREFIXES};
use crate::gen::Generated;
use crate::schema::{Entry, FieldType, Location, Storage, Struct, Word};

/// Where the emitter writes, relative to the workspace root.
pub const PATH: &str = "crates/render/frag/generated/payload_unpack.wgsl";

/// The word buffer's `.w`, whose accessors [`fgw`] writes.
const FGW_WORD: &str = "fgw_w";

/// The emitter: the unpack layer for the payload structs ([`crate::payload::structs`]), or nothing if the layout
/// declares none of their members, as [`rust::emit`] does.
pub fn emit(words: &[Word], entries: &[Entry]) -> Vec<Generated> {
    let structs = crate::payload::structs();
    if !rust::declares(&structs, words, entries) {
        return Vec::new();
    }
    let mut out = String::from(
        "// Generated by `cargo xtask codegen` from the layout table (`crates/ledger/src/payload.rs`); do not edit.\n\
         // The fragment-side unpack layer (render contract Part 5; payload §6, R-86). WGSL: u32 `extractBits` only, no\n\
         // f64, f16 pairs through core `unpack2x16float` (no `enable f16`).\n",
    );
    out.push_str(&version(words, entries, &structs));
    for s in structs.iter().filter(|s| !is_word_buffer(s)) {
        out.push_str(&layout(s));
    }
    out.push_str(&pair_accessors(&structs));
    out.push_str(&bindings(&structs));
    out.push_str(&state_codes());
    out.push_str(&accessors(words, entries));
    out.push_str(&helpers());
    out.push_str(&continuation());
    vec![Generated {
        path: PathBuf::from(PATH),
        contents: out,
    }]
}

/// Whether `s` is the word buffer's element, which the layer binds as `array<vec4<u32>>`, not as a struct.
fn is_word_buffer(s: &Struct) -> bool {
    s.buffer == Some("word")
}

/// The payload schema version (R-36, R-63) as `vec2<u32>`, `.x` its low 32 bits and `.y` its high 32: WGSL has no u64
/// (RQ-188, option 3a).
fn version(words: &[Word], entries: &[Entry], structs: &[Struct]) -> String {
    use crate::version::{schema_version, Hashed};
    match schema_version(&Hashed::payload(words, entries, structs)) {
        Ok(v) => format!(
            "\n// The payload schema version: the 64-bit FNV-1a hash of the canonicalised ledger (R-36, R-63; the Rust\n\
             // PAYLOAD_SCHEMA_VERSION, {v:#018x}). WGSL has no u64: .x is its low 32 bits, .y its high 32 (waiting on\n\
             // RQ-188).\n\
             const PAYLOAD_SCHEMA_VERSION: vec2<u32> = vec2<u32>({:#010x}u, {:#010x}u);\n",
            v & 0xffff_ffff,
            v >> 32,
        ),
        Err(e) => format!("\nconst_assert false; // {e}\n"),
    }
}

/// One WGSL member of a struct: its name, its type, and the ledger members it stores.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WgslMember {
    pub name: String,
    pub ty: String,
    /// The ledger members this one stores, in order: one, or a u16 pair.
    pub stores: Vec<&'static str>,
}

/// `s`'s members as WGSL writes them. A storage maps to its WGSL type; two u16 members in a row, which WGSL cannot
/// store apart (it has no u16), are one u32 named `<first>_<second>`, its leading `_` dropped, the first in bits 0–15
/// (RQ-188, option 2a).
pub fn members(s: &Struct) -> Vec<WgslMember> {
    let mut out = Vec::new();
    let mut i = 0;
    while i < s.members.len() {
        let m = &s.members[i];
        let next = s.members.get(i + 1);
        if m.storage == Storage::U16 {
            if let Some(n) = next.filter(|n| n.storage == Storage::U16) {
                out.push(WgslMember {
                    name: format!("{}_{}", m.name, n.name.trim_start_matches('_')),
                    ty: "u32".to_owned(),
                    stores: vec![m.name, n.name],
                });
                i += 2;
                continue;
            }
        }
        let ty = match m.storage {
            Storage::F32 => "f32".to_owned(),
            // A u16 with no u16 beside it has no WGSL type: the name written is none, so naga refuses the file.
            Storage::U16 => "u16_has_no_wgsl_type".to_owned(),
            Storage::U32 => "u32".to_owned(),
            Storage::Vec2x3 => "array<vec2<f32>, 3>".to_owned(),
            Storage::U32x4 => "vec4<u32>".to_owned(),
            Storage::Pad(n) => format!("array<u32, {n}>"),
        };
        out.push(WgslMember {
            name: m.name.to_owned(),
            ty,
            stores: vec![m.name],
        });
        i += 1;
    }
    out
}

/// `s` as a WGSL struct, its size and alignment in a comment.
fn layout(s: &Struct) -> String {
    let (_, size) = rust::offsets(s);
    let ms = members(s);
    let mut out = format!(
        "\n// `{}`: {size} B, aligned to {} (payload §1; dd_generation_root §3.3a, §3.6).\nstruct {} {{\n",
        s.name, s.align, s.name
    );
    for m in &ms {
        let note = match m.stores.as_slice() {
            [a, b] => format!(
                " // `{a}` in bits 0–15, `{b}` in bits 16–31 (WGSL has no u16; waiting on RQ-188)"
            ),
            _ => String::new(),
        };
        let _ = writeln!(out, "    {}: {},{note}", m.name, m.ty);
    }
    out.push_str("}\n");
    out
}

/// An accessor for each u16 a pair member stores ([`members`]) whose name has no leading `_`, once however many structs
/// store it: `fn <name>(w: u32) -> u32`, its bits through the u32 `extractBits`. The name is the ledger member's.
fn pair_accessors(structs: &[Struct]) -> String {
    let mut out = String::new();
    let mut seen: Vec<&str> = Vec::new();
    for s in structs {
        for m in members(s).iter().filter(|m| m.stores.len() == 2) {
            for (half, name) in m.stores.iter().enumerate() {
                if name.starts_with('_') || seen.contains(name) {
                    continue;
                }
                seen.push(name);
                let offset = 16 * half;
                let _ = write!(
                    out,
                    "\n// `{name}`: bits {offset}–{} of `{}` (payload §1; waiting on RQ-188).\n\
                     fn {name}(w: u32) -> u32 {{ return extractBits(w, {offset}u, 16u); }}\n",
                    offset + 15,
                    m.name,
                );
            }
        }
    }
    out
}

/// The `SimState` buffer and the word buffer, each its own binding, and their reads by the sample index `i`: the word
/// buffer is indexed identically to samples, per copy (render contract Part 5; dd_generation_root §3.3a). The bound
/// `SimState` element is the indexed variant, `SimStateFTLE`; the bindings and the variant wait on RQ-188 (option 1a).
fn bindings(structs: &[Struct]) -> String {
    let state = structs
        .iter()
        .find(|s| s.buffer == Some("SimState") && s.indexed)
        .map_or("SimStateFTLE", |s| s.name);
    format!(
        "\n// The two buffers (payload §0), each its own binding; word_buffer[i] is the word of the sample whose state is\n\
         // simstate_buffer[i] (dd_generation_root §3.3a). Group, binding numbers and the bound variant wait on RQ-188.\n\
         @group(0) @binding(0) var<storage, read> simstate_buffer: array<{state}>;\n\
         @group(0) @binding(1) var<storage, read> word_buffer: array<vec4<u32>>;\n\
         \n// Sample `i`'s stored state.\n\
         fn sample_state(i: u32) -> {state} {{ return simstate_buffer[i]; }}\n\
         \n// Sample `i`'s word: the same index as its state, per copy.\n\
         fn sample_word(i: u32) -> vec4<u32> {{ return word_buffer[i]; }}\n"
    )
}

/// Payload §2's `state` codes as constants, `STATE_<NAME>`, from the ledger's table ([`crate::payload::states`]).
fn state_codes() -> String {
    let mut out = String::new();
    for (code, name) in crate::payload::states().iter().enumerate() {
        let _ = write!(
            out,
            "\n// The `state` code of {name} (payload §2).\nconst STATE_{}: u32 = {code}u;\n",
            name.to_uppercase()
        );
    }
    out
}

/// The accessor prefix of `entry` in `word`, as [`rust`]'s: `sd` for the unsigned fields of `packed_a`.
fn prefix(word: &str, entry: &Entry) -> Option<&'static str> {
    let (_, p) = PREFIXES.iter().find(|(w, _)| *w == word)?;
    Some(if *p == "pa" && entry.ty == FieldType::UBits {
        "sd"
    } else {
        p
    })
}

/// The read accessors of the packed words, one per field, named as payload §6 (`<prefix>_<field>(w: u32)`):
/// - an `f16-pair` field reads `unpack2x16float(w)`'s `.x` (bits 0–15) or `.y` (bits 16–31); a field elsewhere has no
///   WGSL read and fails the file with a `const_assert`;
/// - a 1-bit field is a `bool`, `extractBits(w, o, 1u) == 1u`; any other a u32, `extractBits(w, o, n)`;
/// - a u32 sentinel is `<PREFIX>_<FIELD>_SENTINEL`; an `f16-pair` sentinel of +∞ (`d_min`'s unset value, R-271) is
///   tested by its bits, `<prefix>_<field>_is_unset(w)` against `<PREFIX>_<FIELD>_UNSET`, `0x7c00u`, never by a float
///   comparison.
///
/// The fragment side only reads, so no setter is written. The word buffer's `.w` is [`fgw`]'s.
fn accessors(words: &[Word], entries: &[Entry]) -> String {
    let mut out = String::new();
    for word in words {
        if word.name == FGW_WORD {
            out.push_str(&fgw(entries));
            continue;
        }
        let mut fields: Vec<(&Entry, u32, u32)> = entries
            .iter()
            .filter_map(|e| match e.location {
                Location::Packed {
                    word: w,
                    offset,
                    width,
                } if w == word.name => Some((e, offset, width)),
                _ => None,
            })
            .collect();
        fields.sort_by_key(|&(_, offset, _)| offset);
        for (e, offset, width) in fields {
            let Some(p) = prefix(word.name, e) else {
                continue;
            };
            let (w, f) = (word.name, e.name);
            let bits = match width {
                1 => format!("bit {offset} of `{w}`"),
                _ => format!("bits {offset}–{} of `{w}`", offset + width - 1),
            };
            let upper = format!("{p}_{f}").to_uppercase();
            let (ty, get) = match (&e.ty, offset, width) {
                (FieldType::F16Pair, 0, 16) => ("f32", "unpack2x16float(w).x".to_owned()),
                (FieldType::F16Pair, 16, 16) => ("f32", "unpack2x16float(w).y".to_owned()),
                (FieldType::F16Pair, _, _) => {
                    let _ = write!(
                        out,
                        "\nconst_assert false; // `{f}`: an f16 pair is bits 0–15 or 16–31, not {bits}\n"
                    );
                    continue;
                }
                (_, _, 1) => ("bool", format!("extractBits(w, {offset}u, 1u) == 1u")),
                _ => ("u32", format!("extractBits(w, {offset}u, {width}u)")),
            };
            match (e.ty == FieldType::F16Pair, e.sentinel) {
                (true, Some(s)) if s == f64::INFINITY => {
                    let _ = write!(
                        out,
                        "\n// `{f}`'s unset bits: f16 +∞, the minimum of an empty set (R-271).\n\
                         const {upper}_UNSET: u32 = 0x7c00u;\n\
                         \n// Whether `{f}` is unset: tested by its bits, never by a float comparison (R-271).\n\
                         fn {p}_{f}_is_unset(w: u32) -> bool {{ return extractBits(w, {offset}u, {width}u) == {upper}_UNSET; }}\n"
                    );
                }
                (true, Some(s)) => {
                    let _ = write!(
                        out,
                        "\n// `{f}`'s sentinel in the ledger (dd_generation_root §3.8).\nconst {upper}_SENTINEL: f32 = {s:?};\n"
                    );
                }
                (false, Some(s)) => {
                    let _ = write!(
                        out,
                        "\n// `{f}`'s sentinel in the ledger (dd_generation_root §3.8).\nconst {upper}_SENTINEL: u32 = {}u;\n",
                        s as u64
                    );
                }
                (_, None) => {}
            }
            let _ = write!(
                out,
                "\n// `{f}`: {bits} (payload §2, §6).\nfn {p}_{f}(w: u32) -> {ty} {{ return {get}; }}\n"
            );
        }
    }
    out
}

/// The word buffer's accessors, from `fgw_w`'s `length` entry (payload §3, §6; R-86's names), each taking the whole
/// `vec4<u32>` and reading its `.w`: `FGW_CAPACITY`, `FGW_LENGTH_SENTINEL`, `fgw_length_raw`, `fgw_truncated`,
/// `fgw_reduced_length_valid`, `fgw_reduced_length` and `fgw_retained_prefix_length`. A ledger whose entry lacks what
/// they need is refused by the driver ([`rust::fgw_problem`]); an emitter called past it writes a `const_assert`.
fn fgw(entries: &[Entry]) -> String {
    let (offset, width, capacity, sentinel) = match rust::fgw_length(entries) {
        Ok(length) => length,
        Err(why) => return format!("\nconst_assert false; // {why}\n"),
    };
    format!(
        r"
// The word's capacity in symbols, `length`'s greatest valid value (payload §3).
const FGW_CAPACITY: u32 = {capacity}u;

// `length`'s sentinel in the ledger: the word is truncated (payload §3; dd_generation_root §3.8).
const FGW_LENGTH_SENTINEL: u32 = {sentinel}u;

// `length_raw`: bits {offset}–{last} of the word's `.w`; 0…{capacity} valid, {sentinel} truncated (payload §3).
fn fgw_length_raw(word: vec4<u32>) -> u32 {{ return extractBits(word.w, {offset}u, {width}u); }}

// Whether the word is truncated: `length_raw` is the sentinel (payload §3).
fn fgw_truncated(word: vec4<u32>) -> bool {{ return fgw_length_raw(word) == FGW_LENGTH_SENTINEL; }}

// Whether the reduced crossing count is valid: only when not truncated (payload §5, §6).
fn fgw_reduced_length_valid(word: vec4<u32>) -> bool {{ return !fgw_truncated(word); }}

// The reduced crossing count; use only when `fgw_reduced_length_valid` (payload §6).
fn fgw_reduced_length(word: vec4<u32>) -> u32 {{ return fgw_length_raw(word); }}

// The retained prefix's length, the sentinel clamped to the capacity; debug and export only (payload §6, R-86).
fn fgw_retained_prefix_length(word: vec4<u32>) -> u32 {{ return select(fgw_length_raw(word), FGW_CAPACITY, fgw_truncated(word)); }}
",
        last = offset + width - 1,
    )
}

/// Payload §6's accessors that no single entry determines: the state predicates, over the `STATE_*` codes,
/// `sd_last_symbol_valid` (the register's `fgw_length_sentinel`), `total_substeps_log2` and the `times` fractions.
fn helpers() -> String {
    let truncated = crate::constants::FGW_LENGTH_SENTINEL.number() as u32;
    format!(
        r"
// Escape, bounded or collision: a resolved outcome. sim_failed and decode_failed are finished but not resolved, so
// never gate re-dispatch on this (payload §6).
fn sd_is_resolved_outcome(w: u32) -> bool {{
    let s = sd_state(w);
    return s == STATE_ESCAPE || s == STATE_BOUNDED || s == STATE_COLLISION;
}}

// Still marching: `STATE_RUNNING` (payload §6).
fn sd_is_running(w: u32) -> bool {{ return sd_state(w) == STATE_RUNNING; }}

// Untrusted: neither a resolved outcome nor running, so sim_failed, decode_failed and the reserved codes (payload §2, §6).
fn sd_is_failed(w: u32) -> bool {{ return !sd_is_resolved_outcome(w) && !sd_is_running(w); }}

// Finished, so the scheduler stops marching it: every state but running, the reserved 6–7 included (payload §6).
fn sd_is_finished(w: u32) -> bool {{ return !sd_is_running(w); }}

// Whether `last_symbol` is meaningful, from the sidecar word's `fgw_length_raw`: at least 1 and not the truncation
// sentinel (payload §2, §6).
fn sd_last_symbol_valid(len: u32) -> bool {{ return len >= 1u && len != {truncated}u; }}

// The complexity proxy, floor(log2 total) and 0 for a total ≤ 1, derived from the exact `total_substeps` (payload §6,
// R-86); max() avoids unsigned underflow in the unused branch.
fn total_substeps_log2(total: u32) -> u32 {{ return select(0u, 31u - countLeadingZeros(max(total, 1u)), total > 1u); }}

// `t_end_step / horizon_steps`, 0 when `horizon_steps` is 0 (payload §6).
fn tm_t_end_fraction(w: u32, horizon_steps: u32) -> f32 {{
    return select(0.0, f32(tm_t_end_step(w)) / f32(horizon_steps), horizon_steps > 0u);
}}

// `t_dmin_step / horizon_steps`, 0 when `horizon_steps` is 0 (payload §6).
fn tm_t_dmin_fraction(w: u32, horizon_steps: u32) -> f32 {{
    return select(0.0, f32(tm_t_dmin_step(w)) / f32(horizon_steps), horizon_steps > 0u);
}}
"
    )
}

/// `row` as a WGSL array expression, `array<u32, 4>(a, b, c, d)`.
fn row(r: &[u32; 4]) -> String {
    format!("array<u32, 4>({}u, {}u, {}u, {}u)", r[0], r[1], r[2], r[3])
}

/// `rows` as a WGSL array of rows.
fn rows(rs: &[[u32; 4]]) -> String {
    let inner: Vec<String> = rs.iter().map(row).collect();
    format!("array<array<u32, 4>, {}>({})", rs.len(), inner.join(", "))
}

/// Payload §3's frozen continuation table, from the ledger's ([`crate::payload`]), as shader constants: `INVERSE`,
/// `CONT_SYMBOL`, `PREDECESSOR_SYMBOL` and `CONTINUATION_INDEX` (3 in its four `next = inverse(prev)` cells, R-307);
/// and §3's table functions over them, `inverse`, `continuation_symbol`, `predecessor_symbol` and
/// `continuation_index`. Each is total (R-321, R-324): a symbol input is masked to 2 bits (`& 3u`) and a digit clamped
/// (`min(e, 2u)`) before the table is read, so an input out of range reads the cell at the masked or clamped input, as
/// the Rust release build does. WGSL has no `debug_assert!`.
pub fn continuation() -> String {
    use crate::payload::{cont_symbol, continuation_index, inverse, predecessor_symbol};
    format!(
        r"
// Payload §3's frozen `inverse` (symbol codes a = 0, A = 1, b = 2, B = 3): part of the binary format.
const INVERSE: array<u32, 4> = {};

// Payload §3's frozen `cont_symbol`: next = CONT_SYMBOL[digit][prev].
const CONT_SYMBOL: array<array<u32, 4>, 3> = {};

// `predecessor_symbol`, prev = PREDECESSOR_SYMBOL[digit][next]: CONT_SYMBOL inverted, so equal to it (payload §3).
const PREDECESSOR_SYMBOL: array<array<u32, 4>, 3> = {};

// `continuation_index`, digit = CONTINUATION_INDEX[prev][next]: CONT_SYMBOL inverted, and 3 (invalid) where
// next = inverse(prev) (R-307, payload §3).
const CONTINUATION_INDEX: array<array<u32, 4>, 4> = {};

// The inverse of symbol `s`; `s` masked to 2 bits (R-321).
fn inverse(s: u32) -> u32 {{ return INVERSE[s & 3u]; }}

// The symbol digit `e` continues `prev` with; `prev` masked to 2 bits (R-321), `e` clamped to 2 (R-324).
fn continuation_symbol(prev: u32, e: u32) -> u32 {{ return CONT_SYMBOL[min(e, 2u)][prev & 3u]; }}

// The `prev` that digit `e` continued to `next`, the reverse table a cancellation-pop reads; `next` masked to 2 bits
// (R-321), `e` clamped to 2 (R-324).
fn predecessor_symbol(next: u32, e: u32) -> u32 {{ return PREDECESSOR_SYMBOL[min(e, 2u)][next & 3u]; }}

// The digit that continues `prev` with `s`, 3 where s = inverse(prev) (R-307); each input masked to 2 bits (R-321).
fn continuation_index(prev: u32, s: u32) -> u32 {{ return CONTINUATION_INDEX[prev & 3u][s & 3u]; }}
",
        row(&inverse()),
        rows(&cont_symbol()),
        rows(&predecessor_symbol()),
        rows(&continuation_index()),
    )
}
