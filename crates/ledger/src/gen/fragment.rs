//! The fragment words emitter (TASK-M2-25; R-116): writes the kernel's `generated/fragment_words.rs`, each of
//! [`crate::fragment`]'s layouts as constants, `<LAYOUT>_<PART>` the part's offset and `<LAYOUT>_WORDS` the size,
//! which `kernel::stage::fragment` sizes and indexes its entry points' words by.

use std::fmt::Write as _;
use std::path::PathBuf;

use crate::fragment::layouts;
use crate::gen::Generated;
use crate::schema::{Entry, Word};

/// Where the file is written, relative to the workspace root.
pub const FRAGMENT_WORDS_PATH: &str = "crates/kernel/src/generated/fragment_words.rs";

/// The emitter [`crate::gen::EMITTERS`] runs: the one file.
pub fn emit(_words: &[Word], _entries: &[Entry]) -> Vec<Generated> {
    vec![Generated {
        path: PathBuf::from(FRAGMENT_WORDS_PATH),
        contents: file(),
    }]
}

/// The file's text.
pub fn file() -> String {
    let mut out = String::from(
        "//! Generated by `cargo xtask codegen` from the fragment words' layouts (`crates/ledger/src/fragment.rs`;\n\
         //! `crates/ledger/src/gen/fragment.rs`); do not edit.\n\
         //!\n\
         //! Each fragment entry point's words (`crate::stage::fragment`): a part's offset, and the layout's size.\n",
    );
    for layout in layouts() {
        for p in &layout.parts {
            let _ = write!(
                out,
                "\n/// The {} words: `{}`, {} word(s), from here.\npub const {}_{}: usize = {};\n",
                layout.name.to_lowercase(),
                p.name.to_lowercase(),
                p.len,
                layout.name,
                p.name,
                layout.at(p.name)
            );
        }
        let _ = write!(
            out,
            "\n/// The {} words: their number.\npub const {}_WORDS: usize = {};\n",
            layout.name.to_lowercase(),
            layout.name,
            layout.words()
        );
    }
    out
}
