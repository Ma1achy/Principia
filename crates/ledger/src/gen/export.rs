//! The host export decoder's emitter (render contract Part 5, "(c) the CPU (Rust host) export decoder";
//! dd_generation_root §1, §4 seam 13; RQ-217): writes `crates/engine/src/export/generated.rs`, a Rust decoder of every
//! ledger field from the packed payload, into the engine, the host crate (systems_architecture §7.1).
//!
//! `Decoded` holds one member per ledger entry, in the ledger's order; `decode` fills it from one stored sample at the
//! full tier, `SimStateFTLE`, its word and its `ICDescriptor`. A field the read side holds is read through the Rust
//! read side (lowering Part 3a), so through the same accessors the fragment's read side and the debug catalogue's
//! tests use ([`super::catalogue::read`]); a word field through its word accessor; the Benettin shadow, which the read
//! side does not hold, from the stored struct; an `ICDescriptor` field from the descriptor. A vector is flattened,
//! component `2j` and `2j+1` of slot `j` (dd_generation_root §3.8). A field none of these reads refuses generation
//! ([`refused`]), naming it.

use std::fmt::Write as _;
use std::path::PathBuf;

use crate::gen::catalogue::{self, Read};
use crate::gen::{rust, Generated};
use crate::schema::{Entry, Storage, Word};

/// Where the emitter writes, relative to the workspace root.
pub const PATH: &str = "crates/engine/src/export/generated.rs";

/// The Rust type `e` decodes to, and its value from `read`, `s`, `word` and `ic`, as [`catalogue::Read::rust`] reads
/// it: a vector, three `vec2<f32>` (`Vec2x3`, R-86), flattened to its six components; a stored member as its storage's
/// Rust type.
fn decoded(e: &Entry, r: &Read) -> (String, String) {
    let value = r.rust(e.name);
    match r {
        Read::Member { wgsl, .. } => ((*wgsl).to_owned(), value),
        Read::Vector
        | Read::Stored {
            storage: Storage::Vec2x3,
        } => ("[f32; 6]".to_owned(), format!("flat({value})")),
        Read::Word { .. } => ("u32".to_owned(), value),
        Read::Stored { storage } => (storage.rust(), value),
        Read::Ic => ("f32".to_owned(), value),
    }
}

/// A line for each entry the host has no read of: generation refuses it, naming the field.
pub fn refused(words: &[Word], entries: &[Entry]) -> Vec<String> {
    if !rust::declares(&crate::payload::structs(), words, entries) {
        return Vec::new();
    }
    entries
        .iter()
        .filter(|e| catalogue::read(words, entries, e).is_none())
        .map(|e| {
            format!(
                "field `{}` has no export decoding: neither the read side, the word, the stored struct nor \
                 `ICDescriptor` holds it (render contract Part 5; dd_generation_root §4, seam 13)",
                e.name
            )
        })
        .collect()
}

/// The emitter: the export decoder, or nothing for a layout that declares none of the payload structs' members.
pub fn emit(words: &[Word], entries: &[Entry]) -> Vec<Generated> {
    if !rust::declares(&crate::payload::structs(), words, entries) {
        return Vec::new();
    }
    let fields: Vec<(&Entry, String, String)> = entries
        .iter()
        .filter_map(|e| {
            let r = catalogue::read(words, entries, e)?;
            let (ty, value) = decoded(e, &r);
            Some((e, ty, value))
        })
        .collect();
    let mut out = String::from(
        "//! Generated by `cargo xtask codegen` from the layout table (`crates/ledger/src/payload.rs`); do not edit.\n\
         //! The host export decoder (render contract Part 5 (c); dd_generation_root §1, seam 13): every ledger field of\n\
         //! one sample decoded from the packed payload.\n\n\
         use kernel::payload::*;\n\n\
         /// Every ledger field of one sample, decoded: one member per entry, in the ledger's order (dd_generation_root\n\
         /// §3). A vector is flat, component `2j` and `2j + 1` from slot `j` (§3.8).\n\
         #[derive(Clone, Copy, Debug, PartialEq)]\n\
         pub struct Decoded {\n",
    );
    for (e, ty, _) in &fields {
        let _ = writeln!(out, "    pub {}: {ty},", e.name);
    }
    out.push_str(
        "}\n\n\
         /// The stored sample `s`, its word `word` and its `ICDescriptor` `ic`, decoded at `params`: each field the read side\n\
         /// holds through the Rust read side (lowering Part 3a), the word bound and E = 0, with the descriptor's masses; a word\n\
         /// field through its word accessor; the shadow from `s`; an `ICDescriptor` field from `ic`.\n\
         pub fn decode(s: &SimStateFTLE, word: [u32; 4], ic: &ICDescriptor, params: &ReadParams) -> Decoded {\n    \
         let read = sim_state_from_ftle(\n        s,\n        word,\n        true,\n        canonical_nan(),\n        \
         false,\n        [ic.m0, ic.m1, ic.m2],\n        params,\n    );\n    \
         Decoded {\n",
    );
    for (e, _, value) in &fields {
        let _ = writeln!(out, "        {}: {value},", e.name);
    }
    out.push_str("    }\n}\n");
    if fields.iter().any(|(_, _, v)| v.starts_with("flat(")) {
        out.push_str(
            "\n/// A vec2-grouped vector, flat: slot `j`'s two components at `2j` and `2j + 1` (dd_generation_root §3.8).\n\
             fn flat(v: [[f32; 2]; 3]) -> [f32; 6] {\n    [v[0][0], v[0][1], v[1][0], v[1][1], v[2][0], v[2][1]]\n}\n",
        );
    }
    vec![Generated {
        path: PathBuf::from(PATH),
        contents: out,
    }]
}
