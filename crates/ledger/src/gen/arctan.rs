//! The arctangent's emitter (RQ-628, decided by the orchestrator per R-369, option (a); REQ-ENC-024, R-297): writes
//! the kernel's `generated/arctan.rs`, the fixed-point numbers of the kernel's own f32 `atan2` (`kernel::arctan`),
//! which the kernel adds, subtracts and multiplies in integer arithmetic.
//!
//! - `ATAN_EIGHTHS`: `atan(k/8)` for `k = 0 … 8`, each as a Q0.64 fraction, rounded to nearest, its high word first.
//!   `atan(8/8) = π/4`.
//! - `HALF_PI` and `PI`: `π/2` and `π` as Q2.62 fractions, rounded to nearest, from the same `π/4`.
//! - `ATAN_SERIES`: `1/(2j + 3)` for `j = 0 … 4` as Q0.32 fractions, rounded to nearest: the coefficients of
//!   `(r − atan r)/r³ = 1/3 − r²/5 + r⁴/7 − r⁶/9 + r⁸/11 − …`, which the kernel truncates after five terms.
//!
//! **Exact, and the same on every host.** Each arctangent is summed here in integer arithmetic, never by a float `atan`:
//! Euler's series `atan x = Σₙ (2²ⁿ(n!)²/(2n+1)!)·x^{2n+1}/(1+x²)^{n+1}`, at `x = k/8`, whose terms are positive and
//! fall by `(2n+2)/(2n+3)·x²/(1+x²) ≤ 1/2` each, summed in 2⁻¹⁰⁰ units ([`atan_eighth`]) until a term truncates to 0.
//! Each term is truncated once, so the sum is low by less than one unit per term, fewer than 100 units, far below
//! the 2⁻⁶⁴ the table keeps, and no host's libm reaches the file.

use std::fmt::Write as _;
use std::path::PathBuf;

use crate::constants::ARCTAN_SUM_BITS;
use crate::gen::Generated;
use crate::schema::{Entry, Word};

/// Where the arctangent's numbers are written, relative to the workspace root.
pub const ARCTAN_PATH: &str = "crates/kernel/src/generated/arctan.rs";

/// The emitter [`crate::gen::EMITTERS`] runs: the one file.
pub fn emit(_words: &[Word], _entries: &[Entry]) -> Vec<Generated> {
    vec![Generated {
        path: PathBuf::from(ARCTAN_PATH),
        contents: arctan_file(),
    }]
}

/// The fraction bits of [`atan_eighth`]'s sum, from the register (`arctan_sum_bits`, REQ-GEN-044).
pub fn sum_bits() -> u32 {
    ARCTAN_SUM_BITS.number() as u32
}

/// `atan(k/8)` in units of `2^-sum_bits()`, by Euler's series (the module's note), for `k = 0 … 8`: with
/// `d = 64 + k²`, the first term is `x/(1 + x²) = 8k/d` and each next is the last times `(2n+2)·k²/((2n+3)·d)`.
/// Every product stays below 2¹²⁸: a term is below 2¹⁰⁰, and its factor's numerator, `(2n+2)·k²`, below 2¹⁴ for the
/// at most `sum_bits()` terms the sum takes.
///
/// That count is the loop's bound, derived, never reached with a term left over: the first term is at most
/// `2^(sum_bits() - 1)` (`8k/d ≤ 1/2`) and each next at most half the last, so the term after the first `sum_bits()`
/// has truncated to 0. A bound rather than a `while`, so a broken stopping test ends the sum instead of spinning.
pub fn atan_eighth(k: u32) -> u128 {
    let k = u128::from(k);
    let d = 64 + k * k;
    let mut term = ((8 * k) << sum_bits()) / d;
    let mut sum = 0;
    for n in 0..u128::from(sum_bits()) {
        if term == 0 {
            break;
        }
        sum += term;
        term = term * (2 * n + 2) * k * k / ((2 * n + 3) * d);
    }
    sum
}

/// `v`, in units of `2^-sum_bits()`, rounded to nearest in units of `2^-bits`.
pub fn round_to(v: u128, bits: u32) -> u64 {
    let shift = sum_bits() - bits;
    ((v + (1 << (shift - 1))) >> shift) as u64
}

/// `ATAN_EIGHTHS[k]`: `atan(k/8)` as a Q0.64 fraction.
pub fn eighth_q64(k: u32) -> u64 {
    round_to(atan_eighth(k), 64)
}

/// `HALF_PI`: `π/2 = 2·atan 1` as a Q2.62 fraction.
pub fn half_pi_q62() -> u64 {
    round_to(2 * atan_eighth(8), 62)
}

/// `PI`: `π = 4·atan 1` as a Q2.62 fraction.
pub fn pi_q62() -> u64 {
    round_to(4 * atan_eighth(8), 62)
}

/// `ATAN_SERIES[j]`: `1/(2j + 3)` as a Q0.32 fraction, rounded to nearest.
pub fn series_q32(j: u32) -> u32 {
    let d = u64::from(2 * j + 3);
    (((1u64 << 32) + d / 2) / d) as u32
}

/// Interface data, not a register constant (REQ-SYS-082): the length of the emitted `ATAN_SERIES`, the series' length
/// the kernel evaluates from `ATAN_SERIES[4]` down.
pub fn series_terms() -> u32 {
    5
}

/// `v`'s two words, high first, as hex literals.
fn words(v: u64) -> String {
    let (hi, lo) = ((v >> 32) as u32, v as u32);
    format!("[{}, {}]", hex(hi), hex(lo))
}

/// `w` as a hex literal in groups of four digits.
fn hex(w: u32) -> String {
    format!("0x{:04X}_{:04X}", w >> 16, w & 0xFFFF)
}

/// The arctangent's file.
pub fn arctan_file() -> String {
    let mut s = String::from(
        "//! Generated by `cargo xtask codegen` from `crates/ledger/src/gen/arctan.rs`; do not edit.\n\
         //!\n\
         //! The fixed-point numbers of the kernel's own f32 `atan2` (`crate::arctan`; RQ-628, decided per R-369,\n\
         //! option (a)), each summed by the generator in integer arithmetic, never by a float `atan`, and rounded to\n\
         //! nearest. A two-word number is its high word first.\n\n\
         /// `atan(k/8)` for `k = 0 … 8`, each a Q0.64 fraction: the arctangent's breakpoints, `atan(8/8) = π/4`.\n\
         pub const ATAN_EIGHTHS: [[u32; 2]; 9] = [\n",
    );
    for k in 0..=8 {
        let _ = writeln!(s, "    {},", words(eighth_q64(k)));
    }
    s.push_str("];\n\n/// `π/2`, a Q2.62 fraction.\n");
    let _ = writeln!(s, "pub const HALF_PI: [u32; 2] = {};", words(half_pi_q62()));
    s.push_str("\n/// `π`, a Q2.62 fraction.\n");
    let _ = writeln!(s, "pub const PI: [u32; 2] = {};", words(pi_q62()));
    let _ = write!(
        s,
        "\n/// `1/(2j + 3)` for `j = 0 … {}`, each a Q0.32 fraction: the series `(r − atan r)/r³ = 1/3 − r²/5 + …`.\n\
         pub const ATAN_SERIES: [u32; {}] = [\n",
        series_terms() - 1,
        series_terms()
    );
    for j in 0..series_terms() {
        let _ = writeln!(s, "    {},", hex(series_q32(j)));
    }
    s.push_str("];\n");
    s
}
