//! The host's `N_sub` threshold generator (R-502; REQ-INT-091; dd_integrator §3.3): the sim key's table
//! `THR[n] = round_f32((r_sub·n^{−1/γ_sub})²)`, `n = 1 … L_max`, computed when the sim key is set, never on the device.
//!
//! **One rounding to f32, through a pinned pure-software libm.** Each threshold is evaluated in f64 in one order,
//! `e = −1/γ_sub`, `p = pow(n, e)`, `s = r_sub·p`, `s·s`, each rounded once, the `pow` [`libm::pow`]: libm 0.2.16,
//! exact in `Cargo.lock`, built with `force-soft-floats`, plain Rust over IEEE f64 arithmetic, so neither a platform
//! libm nor a compiler intrinsic nor an architecture's instruction computes it, and the native and the wasm hosts give
//! the same bits (REQ-INT-093 checks the wasm one). The f64 value is then rounded once to f32, and only its bits are
//! shipped. `cargo xtask codegen` evaluates the default sim key's table in the same order on its own path
//! (`ledger::gen::nsub`), and the two agree bit for bit (REQ-INT-092).
//!
//! **Refusals** ([`NsubTableError`]), never a truncation: an `N_max` below 1 or above `L_max`, the table's maximum
//! length (R-502; REQ-INT-094); an `r_sub` or `γ_sub` that is not finite and positive, for which the law has no
//! thresholds; a table that rises anywhere, which the comparison tree, a search over a non-increasing table, cannot
//! read (a rounding of a decreasing sequence never rises, so this guards the f64 evaluation); and a threshold
//! `THR[n]`, `n < N_max`, that is not a normal f32. Those are the thresholds that decide `N_sub`, since every bucket past
//! `N_max − 1` caps to `N_max`; a zero, subnormal or infinite one would be read differently by a backend that flushes
//! subnormals, or compares `d²`, which is 0 or at least `2⁻¹²⁶` (`super::substep::square`), against nothing. The
//! thresholds past `N_max − 1` are still generated by the one formula and shipped, so the table is the same for every
//! `N_max` (R-502).
//!
//! Host code: the SPIR-V build does not take this module (`super`).

use core::fmt;

use spirv_std::glam::UVec4;

use super::substep::NsubThresholds;
use crate::generated::nsub_thresholds::{
    GAMMA_SUB_DEFAULT, NSUB_TABLE_MAX, NSUB_TABLE_ROWS, N_MAX_DEFAULT, R_SUB_DEFAULT,
};
use crate::real::IeeeBits;

/// A sim key's substep law: the three values the table and the cap are made from (integrator_contract Part 3).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct NsubConfig {
    /// `r_sub`, a length.
    pub r_sub: f64,
    /// `γ_sub`, the law's exponent.
    pub gamma_sub: f64,
    /// `N_max`, the substep cap.
    pub n_max: u32,
}

impl NsubConfig {
    /// The defaults, `r_sub = 0.05`, `γ_sub = 1.5`, `N_max = 64` (the constants register's; integrator_contract
    /// Part 3).
    pub const DEFAULT: NsubConfig = NsubConfig {
        r_sub: R_SUB_DEFAULT,
        gamma_sub: GAMMA_SUB_DEFAULT,
        n_max: N_MAX_DEFAULT,
    };
}

/// Why the generator refused a sim key (the module's note). Dispatch returns it (TASK-M3-06).
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum NsubTableError {
    /// `N_max` is 0: a macro-step takes at least one substep.
    NMaxBelowOne,
    /// `N_max` is above `L_max`, the table's maximum length.
    NMaxAboveTable {
        /// The `N_max` asked for.
        n_max: u32,
    },
    /// `r_sub` is not finite and positive.
    RSub {
        /// The `r_sub` given.
        r_sub: f64,
    },
    /// `γ_sub` is not finite and positive.
    GammaSub {
        /// The `γ_sub` given.
        gamma_sub: f64,
    },
    /// `THR[n]` is above `THR[n − 1]`.
    Rises {
        /// The first `n` at which the table rises.
        n: u32,
    },
    /// `THR[n]`, one that decides `N_sub` (`n < N_max`), is not a normal f32.
    NotNormal {
        /// The threshold's index.
        n: u32,
        /// Its bits.
        bits: u32,
    },
}

impl fmt::Display for NsubTableError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match *self {
            Self::NMaxBelowOne => write!(f, "N_max is 0: a macro-step takes at least one substep"),
            Self::NMaxAboveTable { n_max } => write!(
                f,
                "N_max {n_max} is above the threshold table's maximum length, {NSUB_TABLE_MAX} (R-502)"
            ),
            Self::RSub { r_sub } => write!(f, "r_sub {r_sub} is not finite and positive"),
            Self::GammaSub { gamma_sub } => {
                write!(f, "gamma_sub {gamma_sub} is not finite and positive")
            }
            Self::Rises { n } => write!(f, "the thresholds rise at THR[{n}]"),
            Self::NotNormal { n, bits } => write!(
                f,
                "THR[{n}] (bits {bits:#010X}) decides N_sub and is not a normal f32"
            ),
        }
    }
}

/// `THR[n]` at `r_sub` and `gamma_sub` in f64, before its one rounding to f32, in the module's order.
#[inline]
pub fn threshold_f64(r_sub: f64, gamma_sub: f64, n: u32) -> f64 {
    let e = -1.0 / gamma_sub;
    let s = r_sub * libm::pow(f64::from(n), e);
    s * s
}

/// Whether `x` is finite and positive.
#[inline]
fn finite_positive(x: f64) -> bool {
    x.is_finite() && x > 0.0
}

/// Checks the table `bits`, `THR[1] … THR[L_max]`, for a cap of `n_max`: it never rises, and each threshold below
/// `n_max` is a normal f32 (the module's note).
pub fn check_table(bits: &[u32; NSUB_TABLE_MAX], n_max: u32) -> Result<(), NsubTableError> {
    for (i, pair) in bits.windows(2).enumerate() {
        if f32::from_bits(pair[1]) > f32::from_bits(pair[0]) {
            return Err(NsubTableError::Rises { n: i as u32 + 2 });
        }
    }
    for (i, &b) in bits
        .iter()
        .enumerate()
        .take(n_max.saturating_sub(1) as usize)
    {
        let e = f32::from_bits(b).exponent();
        if !(-126..=127).contains(&e) {
            return Err(NsubTableError::NotNormal {
                n: i as u32 + 1,
                bits: b,
            });
        }
    }
    Ok(())
}

/// The sim key's thresholds `THR[1] … THR[L_max]` as f32 bit patterns, or the refusal (the module's note).
pub fn threshold_bits(config: &NsubConfig) -> Result<[u32; NSUB_TABLE_MAX], NsubTableError> {
    let NsubConfig {
        r_sub,
        gamma_sub,
        n_max,
    } = *config;
    if n_max < 1 {
        return Err(NsubTableError::NMaxBelowOne);
    }
    if n_max as usize > NSUB_TABLE_MAX {
        return Err(NsubTableError::NMaxAboveTable { n_max });
    }
    if !finite_positive(r_sub) {
        return Err(NsubTableError::RSub { r_sub });
    }
    if !finite_positive(gamma_sub) {
        return Err(NsubTableError::GammaSub { gamma_sub });
    }
    let mut bits = [0; NSUB_TABLE_MAX];
    for (i, b) in bits.iter_mut().enumerate() {
        *b = (threshold_f64(r_sub, gamma_sub, i as u32 + 1) as f32).to_bits();
    }
    check_table(&bits, n_max)?;
    Ok(bits)
}

/// `bits`, `THR[1] … THR[L_max]`, laid out as `SimUniforms` holds them ([`NsubThresholds`]): `THR[n]` at row
/// `(n − 1)/4`, lane `(n − 1) mod 4`; a lane past `L_max` is 0 and never read.
pub fn pack(bits: &[u32; NSUB_TABLE_MAX]) -> NsubThresholds {
    let mut rows = [UVec4::ZERO; NSUB_TABLE_ROWS];
    for (row, four) in rows.iter_mut().zip(bits.chunks(4)) {
        for (lane, &b) in four.iter().enumerate() {
            row[lane] = b;
        }
    }
    NsubThresholds { rows }
}

/// The sim key's table, packed for `SimUniforms` ([`threshold_bits`], [`pack`]), or the refusal.
pub fn thresholds(config: &NsubConfig) -> Result<NsubThresholds, NsubTableError> {
    Ok(pack(&threshold_bits(config)?))
}
