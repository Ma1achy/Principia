"""Write CITATIONS.md for the Three Body Orbits snapshot.

Usage: python3 -I citations.py threebodyorbits_catalogue.json threebodyorbits_sources.json CITATIONS.md

Each orbit's source is its own `source` field where the catalogue sets one, else its family's, with one correction:
the Li families (`li_*`) mix Li & Liao 2017 (equal masses) with Li, Jing & Liao 2018 (unequal masses) under one
family source, so an unset `li_*` orbit is attributed by its masses. Ricky Reusser's compilation, from which those
orbits come, attributes them the same way ("li-eq", "li-unequal").
"""
import collections
import json
import sys

cat = json.load(open(sys.argv[1]))["orbits"]
src = json.load(open(sys.argv[2]))
S = src["sources"]
F = {k: (v["label"], v["source"]) for k, v in src["families"].items()}


def effective(o):
    if o.get("source"):
        return o["source"]
    if o["family"].startswith("li_"):
        m = o["masses"]
        return "liliao2017" if max(m) - min(m) < 1e-9 else "lijingliao2018"
    return F[o["family"]][1]


cnt = collections.Counter(o["family"] for o in cat)
rows = collections.Counter((o["family"], effective(o)) for o in cat)
stab = collections.defaultdict(collections.Counter)
for o in cat:
    if o.get("stab_src"):
        stab[o["family"]][o["stab_src"]] += 1
moved = sum(1 for o in cat if not o.get("source") and effective(o) != F[o["family"]][1])
alias={'liliao2017-10digit':'liliao2017'}
def ref(k):
    s=S[alias.get(k,k)]
    url=s.get('url','')
    if url.startswith('/'): url='https://www.threebodyorbits.com'+url
    out=f"{s['authors']} ({s['year']}), *{s['title']}*, {s['venue']}"
    if url: out+=f", {url}"
    return out
