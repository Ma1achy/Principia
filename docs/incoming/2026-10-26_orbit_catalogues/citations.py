for k in sorted(J, key=lambda k:(cited(k)['year'],k)):
    j=J[k]
    diff=[f for f in FIELDS if f in j]
    if diff:
        L.append(f"- `{k}`: **the journal**: {ref(k)}. **The site**: {ref(k, S[k])}. Corrected: {', '.join(diff)}.")
    else:
        L.append(f"- `{k}`: the site's wording is the journal's: {ref(k)}.")
    L.append(f"  Checked: {j['checked']} Basis: {j['basis']}.")
